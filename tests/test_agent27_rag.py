class TestTextChunking:
    """Test text chunking functionality."""

    def test_chunk_text_basic(self):
        """Test basic text chunking."""
        text = "A" * 2000  # Long text
        chunks = RAGSystem._chunk_text(text, chunk_size=500)

        assert len(chunks) > 1
        for chunk in chunks:
            assert len(chunk) <= 600  # Allow some overlap

    def test_chunk_overlap(self):
        """Test that chunks have proper overlap."""
        text = "Sentence one. Sentence two. Sentence three. " * 100
        chunks = RAGSystem._chunk_text(text, chunk_size=200, overlap=50)

        # Verify chunks overlap
        if len(chunks) > 1:
            # Some content from chunk 0 should appear in chunk 1
            assert any(word in chunks[1] for word in chunks[0].split()[-10:])

    def test_sentence_boundary_breaking(self):
        """Test that chunks break on sentence boundaries when possible."""
        text = "First sentence. Second sentence. Third sentence. " * 20
        # Use valid parameters: overlap must be < chunk_size
        chunks = RAGSystem._chunk_text(text, chunk_size=100, overlap=50)

        # Most chunks should end with sentence punctuation
        sentence_endings = sum(1 for c in chunks if c.endswith('.'))
        assert sentence_endings > len(chunks) / 2


